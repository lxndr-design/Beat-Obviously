#!/usr/bin/env node
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const SOURCE_REVISION = "7abb3c652525a15dfac80e1b5dfbba9964ee568f";
const REPOSITORY = "sfzinstruments/karoryfer.bear-sax";
const repoRoot = join(import.meta.dirname, "..");
const publicRoot = join(repoRoot, "frontend/public/samples/bear-sax-score");
const generatedTarget = join(repoRoot, "frontend/src/state/factorySaxSamplerManifest.generated.ts");

const treeResponse = await fetch(`https://api.github.com/repos/${REPOSITORY}/git/trees/${SOURCE_REVISION}?recursive=1`);
if (!treeResponse.ok) throw new Error(`Could not read the pinned Bear Sax tree (${treeResponse.status}).`);
const tree = (await treeResponse.json()).tree ?? [];
const soft = tree.filter((entry) => /^Samples\/[a-g](?:b|#)?\d_looped_p\.wav$/i.test(entry.path ?? ""))
  .map((entry) => ({ entry, rootNote: noteNameToMidi(basename(entry.path).split("_")[0]) }))
  .sort((left, right) => left.rootNote - right.rootNote);
const selectedRoots = [...new Set(Array.from({ length: 10 }, (_, index) => soft[Math.round(index * (soft.length - 1) / 9)].rootNote))];
const zones = [];
const checksums = [];
let totalBytes = 0;

for (const rootNote of selectedRoots) {
  const rootName = soft.find((candidate) => candidate.rootNote === rootNote).entry.path.match(/Samples\/(.+)_looped_p\.wav$/i)[1];
  for (const layer of [
    { suffix: "p", loVel: 1, hiVel: 79, label: "soft" },
    { suffix: "f", loVel: 80, hiVel: 127, label: "forte" },
  ]) {
    const path = `Samples/${rootName}_looped_${layer.suffix}.wav`;
    const entry = tree.find((candidate) => candidate.path === path);
    if (!entry) throw new Error(`Pinned Bear Sax sample is missing: ${path}`);
    const fileName = basename(path);
    const destination = join(publicRoot, fileName);
    mkdirSync(publicRoot, { recursive: true });
    if (!existsSync(destination) || statSync(destination).size !== entry.size) {
      const response = await fetch(rawUrl(path));
      if (!response.ok) throw new Error(`Could not download ${path} (${response.status}).`);
      writeFileSync(destination, Buffer.from(await response.arrayBuffer()));
    }
    const bytes = readFileSync(destination);
    totalBytes += bytes.length;
    checksums.push(`${createHash("sha256").update(bytes).digest("hex")}  ${fileName}`);
    zones.push({
      id: `bear-sax-${rootNote}-${layer.loVel}`,
      path: `/samples/bear-sax-score/${fileName}`,
      name: `Bear Sax ${rootName.toUpperCase()} ${layer.label}`,
      rootNote,
      loNote: rootNote,
      hiNote: rootNote,
      loVel: layer.loVel,
      hiVel: layer.hiVel,
      volumeDb: 0,
      pan: 0,
      tuning: 0,
      seqPosition: 0,
      oneShot: false,
    });
  }
}

writeFileSync(join(publicRoot, "SHA256SUMS"), `${checksums.sort().join("\n")}\n`, "utf8");
writeFileSync(join(publicRoot, "LICENSE.txt"), [
  "Bear Sax by Karoryfer Samples",
  `Pinned source: https://github.com/${REPOSITORY}/tree/${SOURCE_REVISION}`,
  "License: CC0 1.0 Universal",
  "Beat packages ten recorded roots with soft and forte sustain layers.",
  "",
].join("\n"), "utf8");
writeFileSync(generatedTarget, [
  "// Generated by scripts/fetch-bear-sax-score-sampler.mjs. Do not edit by hand.",
  `export const BEAR_SAX_SOURCE_REVISION = ${JSON.stringify(SOURCE_REVISION)};`,
  `export const BEAR_SAX_SAMPLE_MAP = ${JSON.stringify(zones, null, 2)} as const;`,
  "",
].join("\n"), "utf8");
console.log(`Bear Sax score sampler: ${zones.length} zones, ${(totalBytes / 1048576).toFixed(1)} MB.`);

function rawUrl(path) {
  const encoded = path.split("/").map(encodeURIComponent).join("/");
  return `https://raw.githubusercontent.com/${REPOSITORY}/${SOURCE_REVISION}/${encoded}`;
}

function noteNameToMidi(value) {
  const match = value.toLowerCase().match(/^([a-g])(b|#)?(\d)$/);
  if (!match) throw new Error(`Unsupported Bear Sax note name: ${value}`);
  const pitchClass = { c: 0, d: 2, e: 4, f: 5, g: 7, a: 9, b: 11 }[match[1]];
  const accidental = match[2] === "b" ? -1 : match[2] === "#" ? 1 : 0;
  return (Number.parseInt(match[3], 10) + 1) * 12 + pitchClass + accidental;
}
