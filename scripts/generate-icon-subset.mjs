#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const repoRoot = new URL("..", import.meta.url).pathname;
const frontendSrc = join(repoRoot, "frontend", "src");
const sourceOut = join(frontendSrc, "solid-ui", "Icon", "phIconSubset.ts");
const iconJsonPath = join(repoRoot, "frontend", "node_modules", "@iconify-json", "ph", "icons.json");
const fallbackIcons = ["ph:square"];

if (!existsSync(iconJsonPath)) {
  throw new Error("Missing @iconify-json/ph. Run `npm install` in frontend before regenerating icons.");
}

const collection = JSON.parse(readFileSync(iconJsonPath, "utf8"));
const names = new Set(fallbackIcons);
const usageSizes = new Map();

for (const file of walk(frontendSrc, (path) => /\.(ts|tsx)$/.test(path) && path !== sourceOut)) {
  const source = readFileSync(file, "utf8");
  for (const match of source.matchAll(/["'](ph:[a-z0-9-]+)["']/g)) {
    names.add(match[1]);
  }
  for (const match of source.matchAll(/<Icon\b[^>]*>/g)) {
    const tag = match[0];
    const name = tag.match(/\bname=["'](ph:[a-z0-9-]+)["']/)?.[1];
    if (!name) continue;
    const size = Number(tag.match(/\bsize=\{(18)\}/)?.[1] ?? 18);
    const sizes = usageSizes.get(name) ?? new Set();
    sizes.add(size);
    usageSizes.set(name, sizes);
  }
}

const icons = {};
const aliases = {};
const missing = [];

function includeIcon(iconName) {
  const name = iconName.replace(/^ph:/, "");
  if (icons[name]) return;
  if (collection.icons?.[name]) {
    icons[name] = collection.icons[name];
    return;
  }
  const alias = collection.aliases?.[name];
  if (alias) {
    aliases[name] = alias;
    includeIcon(`ph:${alias.parent}`);
    return;
  }
  missing.push(iconName);
}

Array.from(names).sort().forEach(includeIcon);

if (missing.length > 0) {
  throw new Error(`Missing Phosphor icons in @iconify-json/ph: ${missing.join(", ")}`);
}

const subset = {
  prefix: "ph",
  icons,
  ...(Object.keys(aliases).length > 0 ? { aliases } : {}),
  width: collection.width ?? 256,
  height: collection.height ?? 256,
};
const serializedUsageSizes = Object.fromEntries(
  Array.from(names)
    .sort()
    .map((name) => [name, Array.from(usageSizes.get(name) ?? [18]).sort((a, b) => a - b)]),
);

mkdirSync(join(frontendSrc, "solid-ui", "Icon"), { recursive: true });
writeFileSync(
  sourceOut,
  [
    "import type { IconifyJSON } from \"@iconify/types\";",
    "",
    "// Generated by scripts/generate-icon-subset.mjs. Do not edit manually.",
    `export const PH_ICON_SUBSET = ${JSON.stringify(subset, null, 2)} as IconifyJSON;`,
    "",
    `export const PH_ICON_USAGE_SIZES = ${JSON.stringify(serializedUsageSizes, null, 2)} as const;`,
    "",
  ].join("\n"),
);

console.log(`Generated ${relative(repoRoot, sourceOut)} with ${Object.keys(icons).length} icons and ${Object.keys(aliases).length} aliases.`);

function walk(dir, predicate = () => true) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      out.push(...walk(full, predicate));
    } else if (predicate(full)) {
      out.push(full);
    }
  }
  return out;
}
